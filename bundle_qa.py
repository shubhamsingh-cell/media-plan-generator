def _check_zero_hire_honesty(wb: Any, findings: list[Finding]) -> None:
    if wb is None:
        return
    for ws in wb.worksheets:
        rows = list(ws.iter_rows(values_only=False))
        for ri, row in enumerate(rows):
            vals = [c.value for c in row]
            hires_col = None
            cph_col = None
            for ci, v in enumerate(vals):
                if isinstance(v, str):
                    vl = v.lower()
                    if hires_col is None and (
                        "proj. hires" in vl or vl.strip() == "hires"
                    ):
                        hires_col = ci
                    if cph_col is None and (
                        "cost per hire" in vl or vl.strip() in ("cph", "cost/hire")
                    ):
                        cph_col = ci
            if hires_col is None or cph_col is None:
                continue
            for dri in range(ri + 1, len(rows)):
                dvals = [c.value for c in rows[dri]]
                if hires_col >= len(dvals) or cph_col >= len(dvals):
                    continue
                hires_val = _cell_num(dvals[hires_col])
                if hires_val is None:
                    continue
                if hires_val == 0:
                    cph_val = dvals[cph_col]
                    cph_num = _cell_num(cph_val)
                    if cph_num is not None and cph_num > 0:
                        findings.append(
                            _finding(
                                "critical",
                                "zero_hire_nonzero_cph",
                                f"Row with 0 projected hires shows a "
                                f"numeric Cost Per Hire ({cph_val!r}) "
                                f"instead of '—'",
                                f"{ws.title}!row{rows[dri][0].row}",
                            )
                        )


