def _cell_num(v: Any) -> float | None:
    if isinstance(v, bool):
        return None
    if isinstance(v, (int, float)):
        return float(v)
    return None


def _check_90_day_forecast_footing(wb: Any, findings: list[Finding]) -> None:
    if wb is None or "90-Day Forecast" not in wb.sheetnames:
        return
    ws = wb["90-Day Forecast"]
    rows = list(ws.iter_rows(values_only=False))

    # Both tables on this sheet ("Monthly Projections Overview" and
    # "Per-Channel Monthly Spend Forecast") follow the same shape: a header
    # row with a label column, 3 month columns, and a "Total"/"90-Day
    # Total" column, followed by data rows until a blank row.
    ri = 0
    while ri < len(rows):
        row = rows[ri]
        vals = [c.value for c in row]
        total_col_idx = None
        for ci, v in enumerate(vals):
            if isinstance(v, str) and "total" in v.lower():
                total_col_idx = ci
                break
        looks_like_header = (
            total_col_idx is not None
            and total_col_idx >= 3
            and any(isinstance(v, str) and v in ("Metric", "Channel") for v in vals)
        )
        if looks_like_header:
            label_col_idx = next(
                (ci for ci, v in enumerate(vals) if v in ("Metric", "Channel")),
                None,
            )
            month_cols = list(range(label_col_idx + 1, total_col_idx))
            data_ri = ri + 1
            while data_ri < len(rows):
                data_row = rows[data_ri]
                dvals = [c.value for c in data_row]
                label = dvals[label_col_idx] if label_col_idx < len(dvals) else None
                if not isinstance(label, str) or not label.strip():
                    break
                # CPA-style *rate* rows are not additive across months --
                # only check rows the generator itself treats as additive
                # (Spend/Applications/Hires/channel-dollar rows never carry
                # "Cost" or "CPA"/"CPH"/"CPC" in the label).
                if not re.search(r"\bcp[achv]\b|cost per", label, re.IGNORECASE):
                    month_vals = [
                        _cell_num(dvals[ci]) if ci < len(dvals) else None
                        for ci in month_cols
                    ]
                    total_val = (
                        _cell_num(dvals[total_col_idx])
                        if total_col_idx < len(dvals)
                        else None
                    )
                    if total_val is not None and all(v is not None for v in month_vals):
                        actual_sum = sum(month_vals)  # type: ignore[arg-type]
                        if abs(actual_sum - total_val) > 0.51:
                            findings.append(
                                _finding(
                                    "critical",
                                    "forecast_footing_mismatch",
                                    f"Row {label!r} monthly values "
                                    f"{month_vals} sum to {actual_sum:,.2f} "
                                    f"but the printed total is "
                                    f"{total_val:,.2f}",
                                    f"{ws.title}!row{data_row[0].row}",
                                )
                            )
                data_ri += 1
            ri = data_ri
            continue
        ri += 1


def _parse_money_str(s: Any) -> float | None:
    if isinstance(s, (int, float)) and not isinstance(s, bool):
        return float(s)
    if not isinstance(s, str):
        return None
    cleaned = re.sub(r"[^0-9.\-]", "", s)
    if not cleaned or cleaned in ("-", "."):
        return None
    try:
        return float(cleaned)
    except ValueError:
        return None


def _check_executive_summary_budget_footing(wb: Any, findings: list[Finding]) -> None:
    if wb is None or "Executive Summary" not in wb.sheetnames:
        return
    ws = wb["Executive Summary"]
    rows = list(ws.iter_rows(values_only=False))

    total_budget: float | None = None
    for ri, row in enumerate(rows):
        vals = [c.value for c in row]
        if any(v == "Total Budget" for v in vals):
            # Value lives one row ABOVE the label, same column (this
            # sheet's KV-block convention -- see excel_v2._write_kv_row).
            label_ci = next(ci for ci, v in enumerate(vals) if v == "Total Budget")
            if ri > 0:
                total_budget = _parse_money_str(rows[ri - 1][label_ci].value)
            break
    if total_budget is None:
        return

    header_row_idx = None
    amount_col = None
    channel_col = None
    for ri, row in enumerate(rows):
        vals = [c.value for c in row]
        if "Channel" in vals and "Amount" in vals:
            header_row_idx = ri
            channel_col = vals.index("Channel")
            amount_col = vals.index("Amount")
            break
    if header_row_idx is None or amount_col is None:
        return

    channel_sum = 0.0
    ri = header_row_idx + 1
    while ri < len(rows):
        vals = [c.value for c in rows[ri]]
        label = vals[channel_col] if channel_col < len(vals) else None
        if not isinstance(label, str) or not label.strip():
            break
        if label.strip().lower() == "total":
            break
        amt = _cell_num(vals[amount_col]) if amount_col < len(vals) else None
        if amt is not None:
            channel_sum += amt
        ri += 1

    if channel_sum and abs(channel_sum - total_budget) > max(1.0, total_budget * 0.005):
        findings.append(
            _finding(
                "critical",
                "exec_summary_budget_footing_mismatch",
                f"Executive Summary channel Amount column sums to "
                f"{channel_sum:,.2f} but the stated Total Budget is "
                f"{total_budget:,.2f}",
                f"{ws.title}!Budget Allocation",
            )
        )


