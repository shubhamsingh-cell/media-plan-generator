def run_bundle_qa(
    pptx_bytes: bytes | None, xlsx_bytes: bytes | None, data: dict
) -> list[Finding]:
    """Lint an already-generated bundle. Never raises -- parse failures and
    all other problems are reported as findings, not exceptions, so callers
    can invoke this unconditionally right after bundle assembly."""
    findings: list[Finding] = []
    data = data if isinstance(data, dict) else {}

    pptx_units: list[_TextUnit] = []
    xlsx_units: list[_TextUnit] = []
    wb = None

    if pptx_bytes:
        try:
            pptx_units = _iter_pptx_texts(pptx_bytes, findings)
        except Exception as exc:  # noqa: BLE001
            findings.append(_finding("critical", "pptx_qa_crashed", f"{exc!r}", "deck"))

    if xlsx_bytes:
        try:
            xlsx_units, wb = _iter_xlsx_strings(xlsx_bytes, findings)
        except Exception as exc:  # noqa: BLE001
            findings.append(
                _finding("critical", "xlsx_qa_crashed", f"{exc!r}", "workbook")
            )

    all_units = pptx_units + xlsx_units
    try:
        _check_text_patterns(all_units, data, findings)
    except Exception as exc:  # noqa: BLE001
        findings.append(_finding("warn", "text_pattern_check_crashed", f"{exc!r}", ""))

    try:
        _check_client_name_casing(all_units, data, findings)
    except Exception as exc:  # noqa: BLE001
        findings.append(_finding("warn", "client_name_check_crashed", f"{exc!r}", ""))

    try:
        _check_comparison_badges(pptx_units, findings)
    except Exception as exc:  # noqa: BLE001
        findings.append(
            _finding("warn", "comparison_badge_check_crashed", f"{exc!r}", "")
        )

    try:
        counter_strings = _collect_pptx_counter_strategies(
            pptx_units
        ) + _collect_xlsx_counter_strategies(wb)
        _check_counter_strategy_distinctness(counter_strings, findings)
    except Exception as exc:  # noqa: BLE001
        findings.append(
            _finding("warn", "counter_strategy_check_crashed", f"{exc!r}", "")
        )

    try:
        _check_90_day_forecast_footing(wb, findings)
    except Exception as exc:  # noqa: BLE001
        findings.append(
            _finding("warn", "forecast_footing_check_crashed", f"{exc!r}", "")
        )

    try:
        _check_executive_summary_budget_footing(wb, findings)
    except Exception as exc:  # noqa: BLE001
        findings.append(
            _finding("warn", "exec_summary_footing_check_crashed", f"{exc!r}", "")
        )

    try:
        _check_zero_hire_honesty(wb, findings)
    except Exception as exc:  # noqa: BLE001
        findings.append(_finding("warn", "zero_hire_check_crashed", f"{exc!r}", ""))

    try:
        _check_recruitment_funnel_footing(wb, findings)
    except Exception as exc:  # noqa: BLE001
        findings.append(
            _finding("warn", "recruitment_funnel_check_crashed", f"{exc!r}", "")
        )

    return findings


