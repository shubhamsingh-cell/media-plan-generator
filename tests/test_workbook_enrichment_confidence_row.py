"""Regression test for the workbook's collector-availability row.

The row describes function-return coverage only. It must not present that
ratio as evidence freshness or quality. The test drives the real workbook and
reads the generated bytes back with openpyxl.
"""

from __future__ import annotations

import io
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

import openpyxl
import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import excel_v2  # noqa: E402
from tests.test_excel_provenance import _minimal_data  # noqa: E402


def _summary(n_called: int, n_ok: int, n_na: int) -> Dict[str, List[str]]:
    labels = [f"S{i}" for i in range(n_called)]
    return {
        "apis_called": labels,
        "apis_succeeded": labels[:n_ok],
        "apis_not_applicable": labels[n_ok : n_ok + n_na],
        "apis_skipped": labels[n_ok : n_ok + n_na],
        "apis_failed": labels[n_ok + n_na :],
    }


def _collector_coverage_row(summary: Dict[str, Any]) -> Tuple[str, str]:
    """Return source text and qualifier of the coverage row."""
    data = _minimal_data(_enriched={"enrichment_summary": summary})
    wb = openpyxl.load_workbook(io.BytesIO(excel_v2.generate_excel_v2(data)))
    ws = wb["Sources & Confidence"]
    for row in ws.iter_rows(values_only=True):
        cells = [c for c in row if c is not None]
        if cells and str(cells[0]).startswith("Collectors returned payloads"):
            return str(cells[0]), str(cells[2])
    raise AssertionError("live-API provenance row not rendered")


@pytest.mark.parametrize(
    "n_called, n_ok, n_na, expected_source, expected_label",
    [
        # The verifier's prod shape: 8 of 10 applicable = 0.80.
        (18, 8, 8, "Collectors returned payloads (8/10 applicable)", "Coverage"),
        # The telemetry run: 10 of 12 applicable = 0.833.
        (18, 10, 6, "Collectors returned payloads (10/12 applicable)", "Coverage"),
        # 5 of 10 applicable = 0.50.
        (18, 5, 8, "Collectors returned payloads (5/10 applicable)", "Coverage"),
        # 3 of 10 applicable = 0.30.
        (18, 3, 8, "Collectors returned payloads (3/10 applicable)", "Coverage"),
    ],
)
def test_collector_row_reports_coverage_without_a_quality_grade(
    n_called: int, n_ok: int, n_na: int, expected_source: str, expected_label: str
) -> None:
    source, label = _collector_coverage_row(_summary(n_called, n_ok, n_na))
    assert (source, label) == (expected_source, expected_label)


def test_sources_sheet_describes_support_without_accuracy_or_freshness_claims() -> None:
    data = _minimal_data(
        _synthesized={
            "confidence_scores": {
                "overall": 0.82,
                "sections": {"salary_intelligence": {"score": 0.8}},
            },
            "_kb_age_days": 0,
        }
    )
    wb = openpyxl.load_workbook(io.BytesIO(excel_v2.generate_excel_v2(data)))
    ws = wb["Sources & Confidence"]
    text = "\n".join(
        str(value)
        for row in ws.iter_rows(values_only=True)
        for value in row
        if value is not None
    )

    assert "DATA SUPPORT ASSESSMENT" in text
    assert "Overall Data Support Score: 82%" in text
    assert "Heuristic support score, not forecast accuracy." in text
    assert "PER-SECTION DATA SUPPORT SCORES" in text
    assert "Data Support Score" in text
    assert "Publication dates vary; see benchmark references." in text
    assert "Every figure in this plan is traceable" not in text
    assert "Overall Confidence" not in text
    assert "Knowledge Base Age" not in text
    assert "0 days old" not in text

    kb_rows = [
        tuple(value for value in row if value is not None)
        for row in ws.iter_rows(values_only=True)
        if "Joveo Knowledge Base (benchmarks)" in row
    ]
    assert kb_rows == [
        (
            "Joveo Knowledge Base (benchmarks)",
            "Publication dates vary",
            "Benchmark",
        )
    ]
