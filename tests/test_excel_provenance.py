def test_confidence_label_normalization():
    assert excel_v2._provenance_confidence_label("measured") == "Measured"
    assert excel_v2._provenance_confidence_label(0.95) == "Verified"
    assert excel_v2._provenance_confidence_label(82) == "High"  # 0-100 tolerated
    assert excel_v2._provenance_confidence_label(None) == "Estimated"
    assert excel_v2._provenance_confidence_label("") == "Estimated"


def test_collect_kb_provenance_dedupes_and_handles_bad_shapes():
    data = {
        "_enriched": {
            "provenance": [
                {"source": "BLS", "vintage": "2025", "confidence": "high"},
                {"source": "BLS", "vintage": "2025", "confidence": "high"},  # dup
                "Plain String Source",
                12345,  # garbage entry ignored
            ]
        },
        "_synthesized": None,  # bad top-level shape tolerated
    }
    rows = excel_v2._collect_kb_provenance(data)
    sources = [r["source"] for r in rows]
    assert sources.count("BLS") == 1
    assert "Plain String Source" in sources


